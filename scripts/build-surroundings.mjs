// Builds public/data/surroundings.json: the Overture building footprints OUTSIDE the campus boundary
// (villages, neighbouring institutes) inside the terrain area. The 3D map draws them as plain low
// houses: no labels, no hit-test. Run: node scripts/build-surroundings.mjs
import fs from 'node:fs';

const SRC = 'reference/overture/export_2026-11-13/overture_buildings.geojson';
const OUT = 'public/data/surroundings.json';
const LIMIT = 1280; // metres from the origin; the terrain grid covers ±1300

const layout = JSON.parse(fs.readFileSync('public/data/campus-layout.json', 'utf8'));
const { lat: LAT0, lon: LON0 } = layout.origin;
const KX = 111320 * Math.cos((LAT0 * Math.PI) / 180), KY = 110574;
const toLocal = ([lon, lat]) => [(lon - LON0) * KX, (lat - LAT0) * KY];

const inPoly = (pt, poly) => {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > pt[1]) !== (yj > pt[1]) && pt[0] < ((xj - xi) * (pt[1] - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const area = p => { let a = 0; for (let i = 0; i < p.length; i++) { const q = p[(i + 1) % p.length]; a += p[i][0] * q[1] - q[0] * p[i][1]; } return a / 2; };

const gj = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const houses = [];
let inside = 0, far = 0, tiny = 0;
for (const f of gj.features) {
  if (f.geometry.type !== 'Polygon') continue;
  let ring = f.geometry.coordinates[0].map(toLocal);
  if (ring.length > 3 && ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1]) ring = ring.slice(0, -1);
  const c = [ring.reduce((s, p) => s + p[0], 0) / ring.length, ring.reduce((s, p) => s + p[1], 0) / ring.length];
  if (Math.abs(c[0]) > LIMIT || Math.abs(c[1]) > LIMIT) { far++; continue; }
  // anything touching the campus is the campus layout's job
  if (inPoly(c, layout.boundary) || ring.some(p => inPoly(p, layout.boundary))) { inside++; continue; }
  let a = area(ring); if (a < 0) { ring.reverse(); a = -a; } // counter-clockwise
  if (a < 6) { tiny++; continue; }
  houses.push({ p: ring.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]), f: a > 320 ? 2 : 1 });
}
fs.writeFileSync(OUT, JSON.stringify({
  note: 'Off-campus building footprints for scenery only (local metres, counter-clockwise). f = floors. Generated by scripts/build-surroundings.mjs.',
  attribution: '© Overture Maps Foundation (Google Open Buildings CC BY 4.0, Microsoft ML Buildings ODbL)',
  houses,
}));
console.log(`surroundings: ${houses.length} houses written (${inside} on campus skipped, ${far} outside the terrain area, ${tiny} tiny), ${(fs.statSync(OUT).size / 1024).toFixed(0)} kB`);
